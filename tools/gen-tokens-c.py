#!/usr/bin/env python3
"""Generate a C header from gride-assets/tokens.json.

tokens.json is the single source of truth for the design language. The
compositor never hard-codes a colour or size: it includes the header this
script writes (gride-tokens.h) at build time.

Usage: gen-tokens-c.py tokens.json output.h
"""

import json
import re
import sys

HEX = re.compile(r"^#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?$")
RGBA = re.compile(r"^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$")
PX = re.compile(r"^(-?\d+(?:\.\d+)?)px$")


def parse_colour(value):
    """Return straight (non-premultiplied) RGBA floats in 0..1."""
    value = value.strip()
    m = HEX.match(value)
    if m:
        rgb = m.group(1)
        r, g, b = (int(rgb[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
        a = int(m.group(2), 16) / 255.0 if m.group(2) else 1.0
        return r, g, b, a
    m = RGBA.match(value)
    if m:
        r, g, b = (float(m.group(i)) / 255.0 for i in (1, 2, 3))
        a = float(m.group(4)) if m.group(4) is not None else 1.0
        return r, g, b, a
    raise ValueError(f"unsupported colour value: {value!r}")


def c_name(name):
    return re.sub(r"[^0-9a-zA-Z]", "_", name).lower()


def px(value):
    m = PX.match(value.strip())
    if not m:
        return None
    return float(m.group(1))


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen-tokens-c.py tokens.json output.h")
    with open(sys.argv[1], encoding="utf-8") as f:
        tokens = json.load(f)

    colours = tokens["color"]["tokens"]
    themes = [t["id"] for t in tokens["color"]["themes"]]

    out = []
    w = out.append
    w("/* Generated by tools/gen-tokens-c.py from gride-assets/tokens.json.")
    w(" * Do not edit: change tokens.json and rebuild. */")
    w("#ifndef GRIDE_TOKENS_H")
    w("#define GRIDE_TOKENS_H")
    w("")
    w("/* Colours are straight (non-premultiplied) RGBA in 0..1. */")
    w("struct gride_palette {")
    for t in colours:
        w(f"\tfloat {c_name(t['name'])}[4];")
    w("};")
    w("")
    for theme in themes:
        w(f"static const struct gride_palette gride_palette_{c_name(theme)} = {{")
        for t in colours:
            r, g, b, a = parse_colour(t["value"][theme])
            w(f"\t.{c_name(t['name'])} = {{ {r:.6f}f, {g:.6f}f, {b:.6f}f, {a:.6f}f }},")
        w("};")
        w("")

    for group in ("spacing", "radius"):
        for t in tokens.get(group, {}).get("tokens", []):
            v = px(t["value"])
            if v is None:
                continue  # percentages such as radius-icon are applied in code
            w(f"#define GRIDE_{c_name(t['name']).upper()} {int(round(v))}")
        w("")

    w("#endif")
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
